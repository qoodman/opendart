def _parse(p):
    p = str(p)
    try:
        if len(p) == 6 and p.isdigit():
            return dt.date(int(p[:4]), int(p[4:]), 28)
        if len(p) == 8 and p.isdigit():
            return dt.date(int(p[:4]), int(p[4:6]), int(p[6:]))
        return dt.date.fromisoformat(p[:10])
    except ValueError:
        return None


def _near(pts, target):
    """날짜가 target 이전인 마지막 점"""
    best = None
    for d, v in pts:
        if d <= target:
            best = (d, v)
        else:
            break
    return best


def _pts(rows):
    out = []
    for p, v in rows:
        d = _parse(p)
        if d and v is not None:
            out.append((d, float(v)))
    return sorted(out)


def indicators(conn):
    """→ dict(rows=[dict(label, value, note)], price='up'|'down'|'flat'|None, rate='up'|'down'|'flat'|None, candidates=[...])"""
    import stock_market as sm
    rows, price, rate = [], None, None
    k = _pts(sm.series(conn, "idx:KOSPI"))
    if len(k) >= 260:
        closes = [v for _, v in k]
        last = closes[-1]
        hi = max(closes[-250:])
        dd = last / hi - 1
        ma = sum(closes[-200:]) / 200
        ma_prev = sum(closes[-220:-20]) / 200
        slope = ma / ma_prev - 1
        r12 = last / closes[-252] - 1
        price = "down" if (last < ma and slope < 0) else "up" if (last > ma and slope > 0) else "flat"
        rows.append(dict(label="코스피 고점 대비 (250거래일)", value=f"{dd:+.1%}", note=f"지금 {last:,.0f} · 고점 {hi:,.0f}"))
        rows.append(dict(label="코스피 200일 이동평균", value=f"{'아래' if last < ma else '위'} · 기울기 {slope:+.1%}", note="가격이 이평선 아래이고 이평선도 내려가면 와인스타인의 4단계(하락)에 가까워요"))
        rows.append(dict(label="코스피 12개월 수익률", value=f"{r12:+.1%}", note=f"기준일 {k[-1][0].isoformat()}"))
    base = _pts(sm.series(conn, "ecos:base_rate"))
    if base:
        cur = base[-1]
        prev = _near(base, cur[0] - dt.timedelta(days=180))
        if prev:
            diff = cur[1] - prev[1]
            rate = "up" if diff > 0.1 else "down" if diff < -0.1 else "flat"
            rows.append(dict(label="기준금리 (6개월 변화)", value=f"{cur[1]:.2f}%  ({diff:+.2f}%p)", note={"up": "인상 구간", "down": "인하 구간", "flat": "동결 구간"}[rate]))
        else:
            rows.append(dict(label="기준금리", value=f"{cur[1]:.2f}%", note=f"기준일 {cur[0].isoformat()}"))
    k3, k10 = _pts(sm.series(conn, "ecos:ktb3")), _pts(sm.series(conn, "ecos:ktb10"))
